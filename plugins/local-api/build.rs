const COMMANDS: &[&str] = &["export_meeting_markdown"];

fn main() {
    // The Tauri plugin generator adds permission files but does not prune removed commands.
    let commands_dir = std::path::Path::new("permissions/autogenerated/commands");
    if let Ok(entries) = std::fs::read_dir(commands_dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            let Some(command) = path.file_stem().and_then(|name| name.to_str()) else {
                continue;
            };
            if !COMMANDS.contains(&command) {
                std::fs::remove_file(path).expect("could not remove stale command permission");
            }
        }
    }
    tauri_plugin::Builder::new(COMMANDS).build();
}
